          depName: 'ghcr.io/example/app',
          currentValue: 'v1.2.3',
          autoReplaceStringTemplate:
            '{{newValue}}{{#if newDigest}}@{{newDigest}}{{/if}}',
          replaceString: 'v1.2.3',
