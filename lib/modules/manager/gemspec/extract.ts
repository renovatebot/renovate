import { logger } from '../../../logger/index.ts';
import { newlineRegex, regEx } from '../../../util/regex.ts';
import { RubygemsDatasource } from '../../datasource/rubygems/index.ts';
import { extractLockFileEntries } from '../bundler/locked-version.ts';
import type { PackageDependency, PackageFileContent } from '../types.ts';
import { findGemspecLockFile } from './lockfile.ts';

const declarationHeadRegex = regEx(
  /^\s*[\w:.]+\.add_(?:runtime_|development_)?dependency\b/,
);

const methodRegex = regEx(
  `^\\s*[\\w:.]+\\.add_(?<type>runtime_|development_)?dependency\\s*\\(?\\s*` +
    `['"](?<depName>[^'"]+)['"]` +
    `(?<rest>[\\s\\S]*)$`,
);

// A name written as a percent literal, e.g. `%q<rack>.freeze` as generated by `gem build`
const percentNameRegex = regEx(
  /^\s*[\w:.]+\.add_(?<type>runtime_|development_)?dependency\s*\(?\s*%[qQ]?[<({[](?<depName>[\w.-]+)[>)}\]]/,
);

// A line that ends inside an argument list, e.g. after `(`, `[` or `,`
const continuationRegex = regEx(/[,([]\s*$/);

// One or more comma-separated quoted constraint strings, e.g. `, "~> 4.2", "!= 4.2.5"`
const constraintsRegex = regEx(/^(?:\s*,\s*['"][^'"]+['"])+$/);

// The same strings wrapped in an array, e.g. `, ["~> 4.2", "!= 4.2.5"]`
const arrayConstraintsRegex = regEx(/^\s*,\s*\[(?<parts>[^\]]*)\]$/);

function stripComment(line: string): string {
  return line.replace(regEx(/#.*$/), '');
}

function stripTail(rest: string): string {
  return stripComment(rest)
    .replace(regEx(/,?\s*\)\s*$/), '') // closing paren of add_dependency(...)
    .trimEnd();
}

function bracketDepth(code: string): number {
  let depth = 0;
  for (const char of code) {
    if (char === '(' || char === '[') {
      depth += 1;
    } else if (char === ')' || char === ']') {
      depth -= 1;
    }
  }
  return depth;
}

function continuesOnNextLine(code: string, depth: number): boolean {
  return depth > 0 || continuationRegex.test(code);
}

/**
 * Returns each dependency declaration, joining the lines of one that wraps.
 * A declaration continues while a bracket is open or its line ends in `(`, `[` or `,`.
 */
function splitDeclarations(content: string): string[] {
  const lineEnding = content.includes('\r\n') ? '\r\n' : '\n';
  const lines = content.split(newlineRegex);
  const declarations: string[] = [];
  for (let i = 0; i < lines.length; i += 1) {
    if (!declarationHeadRegex.test(lines[i])) {
      continue;
    }

    const declaration = [lines[i]];
    let code = stripComment(lines[i]);
    let depth = bracketDepth(code);
    while (
      continuesOnNextLine(code, depth) &&
      i + 1 < lines.length &&
      !declarationHeadRegex.test(lines[i + 1])
    ) {
      i += 1;
      declaration.push(lines[i]);
      code = stripComment(lines[i]);
      depth += bracketDepth(code);
    }
    declarations.push(declaration.join(lineEnding));
  }
  return declarations;
}

/** Returns the quoted constraint list after the gem name, without the leading comma or array brackets. */
function extractConstraints(rest: string): string | null {
  const arrayParts = arrayConstraintsRegex.exec(rest)?.groups?.parts;
  const constraints =
    arrayParts === undefined
      ? rest
      : `, ${arrayParts.trim().replace(regEx(/,$/), '')}`;
  if (!constraintsRegex.test(constraints)) {
    return null;
  }
  // keep the surrounding quotes so ruby versioning can re-quote each part
  return constraints.replace(regEx(/^\s*,\s*/), '').trimEnd();
}

function toDepType(type: string | undefined): string {
  return type === 'development_' ? 'development' : 'runtime';
}

function parseDeclaration(declaration: string): PackageDependency | null {
  const literal = methodRegex.exec(declaration)?.groups;
  if (literal) {
    const { depName } = literal;
    const dep: PackageDependency = {
      depName,
      depType: toDepType(literal.type),
      datasource: RubygemsDatasource.id,
    };
    const tail = stripTail(literal.rest);
    const constraints = extractConstraints(tail);
    if (depName.includes('#{')) {
      dep.skipReason = 'contains-variable';
    } else if (tail.includes('.freeze')) {
      logger.debug(
        `gemspec: frozen string literals are not supported (${depName})`,
      );
      dep.skipReason = 'unsupported';
    } else if (constraints) {
      dep.currentValue = constraints;
    } else {
      dep.skipReason = 'unspecified-version';
    }
    return dep;
  }

  const percent = percentNameRegex.exec(declaration)?.groups;
  if (percent) {
    logger.debug(
      `gemspec: percent-literal gem names are not supported (${percent.depName})`,
    );
    return {
      depName: percent.depName,
      depType: toDepType(percent.type),
      datasource: RubygemsDatasource.id,
      skipReason: 'unsupported',
    };
  }

  logger.debug(`gemspec: cannot read the gem name of: ${declaration.trim()}`);
  return null;
}

function extractDeps(content: string): PackageDependency[] {
  const deps: PackageDependency[] = [];
  for (const declaration of splitDeclarations(content)) {
    const dep = parseDeclaration(declaration);
    if (dep) {
      deps.push(dep);
    }
  }
  return deps;
}

export async function extractPackageFile(
  content: string,
  packageFile?: string,
): Promise<PackageFileContent | null> {
  const deps = extractDeps(content);
  if (!deps.length) {
    return null;
  }

  const res: PackageFileContent = { deps };
  if (!packageFile) {
    return res;
  }

  const lockFile = await findGemspecLockFile(packageFile, content);
  if (!lockFile) {
    return res;
  }

  res.lockFiles = [lockFile.lockFile];
  const lockedVersions = extractLockFileEntries(lockFile.lockFileContent);
  for (const dep of deps) {
    const lockedVersion = lockedVersions.get(dep.depName!);
    if (lockedVersion) {
      dep.lockedVersion = lockedVersion;
    }
  }
  return res;
}
