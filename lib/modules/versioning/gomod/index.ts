import { regEx } from '../../../util/regex.ts';
import { api as semver } from '../semver/index.ts';
import type { VersioningApi } from '../types.ts';
import type { VersionCommit } from './types.ts';

export const id = 'gomod';
export const displayName = 'Go Modules';
export const urls = [
  '[Go Modules Reference: Versions](https://go.dev/ref/mod#versions)',
];
export const supportsRanges = false;

// Same pattern as `IsPseudoVersion()` in golang.org/x/mod/module
const pseudoVersionRegex = regEx(
  /^v\d+\.(?:0\.0-|\d+\.\d+-(?:[^+]*\.)?0\.)\d{14}-[A-Za-z0-9]+(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$/,
);

// Looser than `pseudoVersionRegex`: it also matches versions which only embed
// a commit like one, such as `v1.32.0-20231115204500-e097f827e652.1` of the
// SDKs generated by buf.build
const versionCommitRegex = regEx(
  /v\d+\.\d+\.\d+-(?:\w+\.)?(?:0\.)?(?<timestamp>\d{14})-(?<revision>[a-f0-9]{12})/i,
);

/**
 * Whether the version is a pseudo-version, which Go uses to refer to a commit
 * instead of a tagged release, in any of its three forms:
 * `vX.0.0-yyyymmddhhmmss-abcdefabcdef` without a base version,
 * `vX.Y.Z-pre.0.yyyymmddhhmmss-abcdefabcdef` after a pre-release and
 * `vX.Y.(Z+1)-0.yyyymmddhhmmss-abcdefabcdef` after a release.
 *
 * @see https://go.dev/ref/mod#pseudo-versions
 */
export function isPseudoVersion(version: string | undefined): boolean {
  if (!version) {
    return false;
  }
  return semver.isVersion(version) && pseudoVersionRegex.test(version);
}

/**
 * The commit which the version embeds as `-<timestamp>-<revision>`, like a
 * pseudo-version does, or `null` when it embeds none. Unlike
 * {@link isPseudoVersion} it also accepts versions which only look like a
 * pseudo-version, and placeholders such as
 * `v1.2.3-00010101000000-000000000000`.
 *
 * @see https://go.dev/ref/mod#pseudo-versions
 */
export function parseVersionCommit(version: string): VersionCommit | null {
  const groups = versionCommitRegex.exec(version)?.groups;
  if (!groups) {
    return null;
  }

  return { timestamp: groups.timestamp, revision: groups.revision };
}

export const api: VersioningApi = { ...semver };

export default api;
