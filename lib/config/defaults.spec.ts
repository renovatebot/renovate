import { isNullOrUndefined } from '@sindresorhus/is';
import { partial } from '../../test/util.ts';
import { globalConfigOptionDefaults } from '../global-config-option-defaults.generated.ts';
import type {
  DefaultedConfigKey,
  GlobalDefaultedConfigKey,
  WithDefaults,
} from './defaults.ts';
import {
  getConfig,
  getDefault,
  getGlobalConfigOptionDefaults,
  isDefaultedOption,
  isRepoDefaultedOption,
} from './defaults.ts';
import { globalConfigOptions } from './global-options.ts';
import { getOptions } from './options/index.ts';
import type {
  AllConfig,
  RenovateConfig,
  RenovateConfigFile,
  RenovateOptions,
  StatusCheckKey,
  StatusCheckWhen,
} from './types.ts';

describe('config/defaults', () => {
  describe('getConfig()', () => {
    it('leaves the vulnerabilityAlerts concurrent limit unlimited', () => {
      expect(getConfig().vulnerabilityAlerts).toMatchObject({
        prConcurrentLimit: 0,
      });
    });
  });

  describe('getDefault()', () => {
    it('returns new instances of arrays when called repeatedly', () => {
      const option: RenovateOptions = {
        type: 'array',
        description: 'thing',
        name: 'thing',
        scopes: ['repo'],
      };
      const array1 = getDefault(option);
      const array2 = getDefault(option);

      // Equal values, different objects
      expect(array2).toEqual(array2);
      expect(array1).not.toBe(array2);
    });

    it('returns true for boolean values', () => {
      const option: RenovateOptions = {
        type: 'boolean',
        description: 'thing',
        name: 'thing',
        scopes: ['repo'],
      };
      const val = getDefault(option);

      expect(val).toBe(true);
    });

    it.each(['string', 'object', 'integer'])(
      'returns null for %s values',
      (type: string) => {
        const option = partial<RenovateOptions>({
          type: type as 'string' | 'object' | 'integer',
          description: 'thing',
          name: 'thing',
          scopes: ['repo'],
        });
        const val = getDefault(option);

        expect(val).toBeNull();
      },
    );
  });

  describe('isDefaultedOption()', () => {
    it('selects the options which getConfig() gives a value', () => {
      const config: Record<string, unknown> = { ...getConfig() };

      const options = getOptions();
      const defaultedWithoutValue = options
        .filter(isDefaultedOption)
        .filter((option) => isNullOrUndefined(config[option.name]))
        .map((option) => option.name);
      const otherWithValue = options
        .filter((option) => !isDefaultedOption(option))
        .filter((option) => !isNullOrUndefined(config[option.name]))
        .filter((option) => option.autogenerated !== 'manager')
        .map((option) => option.name);

      expect(defaultedWithoutValue).toEqual([]);
      expect(otherWithValue).toEqual([
        'composerIgnorePlatformReqs',
        'semanticCommitScope',
        'minimumReleaseAgeBuffer',
        'commitMessageTopic',
        'commitMessageExtra',
      ]);
    });
  });

  describe('isRepoDefaultedOption()', () => {
    it.each`
      name                           | expected
      ${'dependencyDashboardTitle'}  | ${true}
      ${'onboarding'}                | ${false}
      ${'extends'}                   | ${false}
      ${'autodiscover'}              | ${false}
      ${'dependencyDashboardFooter'} | ${false}
    `('returns $expected for $name', ({ name, expected }) => {
      const option = getOptions().find((o) => o.name === name)!;

      expect(isRepoDefaultedOption(option)).toBe(expected);
    });
  });

  describe('DefaultedConfigKey', () => {
    it('only contains keys of the config', () => {
      expectTypeOf<
        Exclude<DefaultedConfigKey, keyof AllConfig>
      >().toEqualTypeOf<never>();
    });

    it('follows the rules of getConfig() and getDefault()', () => {
      type Defaulted =
        // a default value
        | 'dependencyDashboardTitle'
        // a boolean without a default value
        | 'onboarding'
        // an array without a default value, in the `any` scope
        | 'ignorePresets'
        // in the top level through its `parents`
        | 'fetchChangeLogs'
        // no `scopes` or `parents`
        | 'allowedHeaders';
      type NotDefaulted =
        // a string without a default value
        | 'dependencyDashboardFooter'
        // an object without a default value
        | 'force'
        // a `null` default value
        | 'dependencyDashboardLabels'
        // `nullable`
        | 'semanticCommitScope'
        // not in the top level
        | 'executionMode';

      expectTypeOf<
        Extract<DefaultedConfigKey, Defaulted | NotDefaulted>
      >().toEqualTypeOf<Defaulted>();
    });
  });

  describe('GlobalDefaultedConfigKey', () => {
    it('follows the global options which are defaulted', () => {
      type Defaulted =
        // a default value
        | 'dockerChildPrefix'
        // a boolean without a default value, which is missing from the generated table of defaults otherwise
        | 'onboarding'
        // a default value, of an option which isn't `globalOnly`
        | 'toolSettings';
      type NotDefaulted =
        // a string without a default value
        | 'endpoint'
        | 'cacheDir'
        | 'dockerCliOptions'
        // not an option
        | 'localDir'
        // a `null` default value
        | 'onboardingAutoCloseAge'
        // not a global option
        | 'dependencyDashboardTitle';

      expectTypeOf<
        Extract<GlobalDefaultedConfigKey, Defaulted | NotDefaulted>
      >().toEqualTypeOf<Defaulted>();
    });
  });

  describe('getGlobalConfigOptionDefaults()', () => {
    it('has the defaults of the global options which are defaulted', () => {
      const expected = Object.fromEntries(
        getOptions()
          .filter(
            (option) =>
              (globalConfigOptions as readonly string[]).includes(
                option.name,
              ) && isDefaultedOption(option),
          )
          .map((option) => [option.name, getDefault(option)]),
      );

      expect(getGlobalConfigOptionDefaults()).toEqual(expected);
      expect(globalConfigOptionDefaults).toEqual(expected);
    });

    it('has the defaults which are not in the options of a global config', () => {
      expect(getGlobalConfigOptionDefaults()).toMatchObject({
        onboarding: true,
        toolSettings: { jvmMaxMemory: 512, jvmMemory: 512 },
      });
    });

    it.each`
      name
      ${'cacheDir'}
      ${'endpoint'}
      ${'localDir'}
      ${'dryRun'}
      ${'onboardingAutoCloseAge'}
    `('leaves out $name, which has no default', ({ name }) => {
      expect(getGlobalConfigOptionDefaults()).not.toHaveProperty(name);
    });
  });

  describe('WithDefaults', () => {
    it('makes the defaulted keys required', () => {
      type Config = WithDefaults<RenovateConfig>;

      expectTypeOf<
        Config['dependencyDashboardTitle']
      >().toEqualTypeOf<string>();
      expectTypeOf<Config['dependencyDashboardFooter']>().toEqualTypeOf<
        string | undefined
      >();
    });

    it('gives the merged defaults of statusCheckWhen all its keys', () => {
      expectTypeOf<RenovateConfigFile['statusCheckWhen']>().toEqualTypeOf<
        Partial<Record<StatusCheckKey, StatusCheckWhen>> | undefined
      >();
      expectTypeOf<RenovateConfig['statusCheckWhen']>().toExtend<
        Record<StatusCheckKey, StatusCheckWhen>
      >();
    });
  });
});
