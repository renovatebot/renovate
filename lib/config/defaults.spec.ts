import { isNullOrUndefined } from '@sindresorhus/is';
import { partial } from '../../test/util.ts';
import type { DefaultedConfigKey, WithDefaults } from './defaults.ts';
import { getConfig, getDefault, isDefaultedOption } from './defaults.ts';
import { getOptions } from './options/index.ts';
import type { AllConfig, RenovateConfig, RenovateOptions } from './types.ts';

describe('config/defaults', () => {
  describe('getConfig()', () => {
    it('leaves the vulnerabilityAlerts concurrent limit unlimited', () => {
      expect(getConfig().vulnerabilityAlerts).toMatchObject({
        prConcurrentLimit: 0,
      });
    });
  });

  describe('getDefault()', () => {
    it('returns new instances of arrays when called repeatedly', () => {
      const option: RenovateOptions = {
        type: 'array',
        description: 'thing',
        name: 'thing',
        scopes: ['repo'],
      };
      const array1 = getDefault(option);
      const array2 = getDefault(option);

      // Equal values, different objects
      expect(array2).toEqual(array2);
      expect(array1).not.toBe(array2);
    });

    it('returns true for boolean values', () => {
      const option: RenovateOptions = {
        type: 'boolean',
        description: 'thing',
        name: 'thing',
        scopes: ['repo'],
      };
      const val = getDefault(option);

      expect(val).toBe(true);
    });

    it.each(['string', 'object', 'integer'])(
      'returns null for %s values',
      (type: string) => {
        const option = partial<RenovateOptions>({
          type: type as 'string' | 'object' | 'integer',
          description: 'thing',
          name: 'thing',
          scopes: ['repo'],
        });
        const val = getDefault(option);

        expect(val).toBeNull();
      },
    );
  });

  describe('isDefaultedOption()', () => {
    it('selects the options which getConfig() gives a value', () => {
      const config: Record<string, unknown> = { ...getConfig() };

      const options = getOptions();
      const defaultedWithoutValue = options
        .filter(isDefaultedOption)
        .filter((option) => isNullOrUndefined(config[option.name]))
        .map((option) => option.name);
      const otherWithValue = options
        .filter((option) => !isDefaultedOption(option))
        .filter((option) => !isNullOrUndefined(config[option.name]))
        .filter((option) => option.autogenerated !== 'manager')
        .map((option) => option.name);

      expect(defaultedWithoutValue).toEqual([]);
      expect(otherWithValue).toEqual([
        'semanticCommitScope',
        'minimumReleaseAgeBuffer',
      ]);
    });
  });

  describe('DefaultedConfigKey', () => {
    it('only contains keys of the config', () => {
      // the options which are only declared on the types of the workers, managers and platforms which read them, so that adding to this list fails
      type Undeclared =
        | 'automergeComment'
        | 'bbAutoResolvePrTasks'
        | 'bbUseDefaultReviewers'
        | 'composerIgnorePlatformReqs'
        | 'excludeCommitPaths'
        | 'forkCreation'
        | 'gitLabIgnoreApprovals'
        | 'goGetDirs'
        | 'ignoreDeprecated'
        | 'ignorePlugins'
        | 'ignoreScripts'
        | 'maxMajorIncrement'
        | 'prBodyTemplate'
        | 'prNotPendingHours'
        | 'replacementApproach'
        | 'updatePinnedDependencies'
        | 'userStrings';

      expectTypeOf<
        Exclude<DefaultedConfigKey, keyof AllConfig>
      >().toEqualTypeOf<Undeclared>();
    });

    it('follows the rules of getConfig() and getDefault()', () => {
      type Defaulted =
        // a default value
        | 'dependencyDashboardTitle'
        // a boolean without a default value
        | 'onboarding'
        // an array without a default value, in the `any` scope
        | 'ignorePresets'
        // in the top level through its `parents`
        | 'fetchChangeLogs'
        // no `scopes` or `parents`
        | 'allowedHeaders';
      type NotDefaulted =
        // a string without a default value
        | 'dependencyDashboardFooter'
        // an object without a default value
        | 'force'
        // a `null` default value
        | 'dependencyDashboardLabels'
        // `nullable`
        | 'semanticCommitScope'
        // not in the top level
        | 'executionMode';

      expectTypeOf<
        Extract<DefaultedConfigKey, Defaulted | NotDefaulted>
      >().toEqualTypeOf<Defaulted>();
    });
  });

  describe('WithDefaults', () => {
    it('makes the defaulted keys required', () => {
      type Config = WithDefaults<RenovateConfig>;

      expectTypeOf<
        Config['dependencyDashboardTitle']
      >().toEqualTypeOf<string>();
      expectTypeOf<Config['dependencyDashboardFooter']>().toEqualTypeOf<
        string | undefined
      >();
    });
  });
});
