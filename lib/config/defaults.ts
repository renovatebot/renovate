import { clone } from '../util/clone.ts';
import { GlobalConfig } from './global.ts';
import type { OptionDefinition } from './options/index.ts';
import { getOptions } from './options/index.ts';
import { getAllowedParents } from './options/scopes.ts';
import { isFilteredOption } from './stages.ts';
import type {
  AllConfig,
  RenovateOptions,
  RepoRemovedConfigKey,
} from './types.ts';

// Use functions instead of direct values to avoid introducing global references.
// In particular, we want a new array instance every time we request a default array
// instead of sharing a single instance - mutation of this value could cause serious problems.
// See https://github.com/mend/renovate-on-prem/issues/290 for an example
const defaultValueFactories = {
  boolean: () => true,
  array: () => [],
  string: () => null,
  object: () => null,
  integer: () => null,
} as const;

export function getDefault(option: RenovateOptions): any {
  return option.default === undefined
    ? defaultValueFactories[option.type]()
    : clone(option.default);
}

function isTopLevelOption(option: RenovateOptions): boolean {
  const parents = getAllowedParents(option);
  return !parents || parents.includes('.');
}

export function getConfig(): AllConfig {
  const options = getOptions();
  const config: AllConfig = {};
  options.forEach((option) => {
    if (isTopLevelOption(option)) {
      config[option.name as keyof AllConfig] = getDefault(option);
    }
  });
  return config;
}

/**
 * Whether an option is one of the {@link DefaultedConfigKey}, by the same rules.
 */
export function isDefaultedOption(option: RenovateOptions): boolean {
  if (
    option.autogenerated === 'manager' ||
    option.nullable ||
    !isTopLevelOption(option)
  ) {
    return false;
  }

  if (option.default === undefined) {
    return option.type === 'boolean' || option.type === 'array';
  }

  return option.default !== null;
}

/**
 * The {@link RepoRemovedConfigKey} options, other than those of the stages before `repository`.
 */
const repoRemovedOptions = [
  ...GlobalConfig.OPTIONS,
  'env',
  'extends',
  'hostRules',
  'ignorePresets',
  'overrideDescription',
] as const satisfies readonly RepoRemovedConfigKey[];

const repoRemovedOptionNames = new Set<string>(repoRemovedOptions);

/**
 * Whether an option is one of the {@link RepoDefaultedConfigKey}, which a repository's config has a value for once its defaults are applied.
 */
export function isRepoDefaultedOption(option: RenovateOptions): boolean {
  return (
    isDefaultedOption(option) &&
    !repoRemovedOptionNames.has(option.name) &&
    !isFilteredOption(option, 'repository')
  );
}

type DeclaredScope<O> = O extends { scopes: readonly (infer S)[] } ? S : never;

type DeclaredParent<O> = O extends { parents: readonly (infer P)[] }
  ? P
  : never;

/**
 * Whether `getConfig()` sets an option, which is when it declares neither `scopes` nor `parents`, or when they include the top level.
 */
type IsTopLevelOption<O> = O extends { scopes: unknown } | { parents: unknown }
  ? [
      | Extract<DeclaredScope<O>, 'repo' | 'any'>
      | Extract<DeclaredParent<O>, '.'>,
    ] extends [never]
    ? false
    : true
  : true;

/**
 * Whether `getDefault()` gives an option a value other than `null`, for an option which isn't `nullable`.
 */
type HasNonNullDefault<O> = O extends { nullable: true }
  ? false
  : O extends { default: infer D }
    ? [D] extends [null]
      ? false
      : true
    : O extends { type: 'boolean' | 'array' }
      ? true
      : false;

type DefaultedOption<O> = O extends unknown
  ? IsTopLevelOption<O> extends true
    ? HasNonNullDefault<O> extends true
      ? O
      : never
    : never
  : never;

/**
 * The options which `getConfig()` gives a value other than `null`, and which can't be configured to `null`.
 *
 * The generated manager options aren't included, as their names aren't known to the type system, and they're read through the manager's config instead.
 */
export type DefaultedConfigKey = DefaultedOption<OptionDefinition>['name'];

/**
 * A config in which the options with a default can't be missing.
 */
export type WithDefaults<T, K extends PropertyKey = DefaultedConfigKey> = T & {
  [P in K & keyof T]-?: NonNullable<T[P]>;
};
